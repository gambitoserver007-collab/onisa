export function getMarketByCountryCode(countryCode?: string | null) {
  return (
    SUPPORTED_MARKETS.find((market) => market.countryCode === countryCode) ??
    SUPPORTED_MARKETS.find((market) => market.countryCode === DEFAULT_MARKET_CODE)!
  );
}

export function formatCurrencyAmount(
  value: number,
  market: Pick<Market, "locale" | "currencyCode"> = getMarketByCountryCode(DEFAULT_MARKET_CODE),
) {
  try {
    return new Intl.NumberFormat(market.locale, {
      style: "currency",
      currency: market.currencyCode,
      currencyDisplay: "narrowSymbol",
    }).format(value);
  } catch {
    return `${market.currencyCode} ${value.toFixed(2)}`;
  }
}

export function getCurrencyLabel(market: Market) {
  const secondary = market.secondaryCurrencyCodes?.length
    ? ` / ${market.secondaryCurrencyCodes.join(", ")}`
    : "";

  return `${market.currencyName} (${market.currencyCode}${secondary})`;
}
